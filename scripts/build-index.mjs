/**
 * Generate the browseable style index used by the `uiux` skill.
 *
 * The index is derived from `data/styles/*.json` so the skill, the tools, and the
 * reference page always describe the same catalog.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { loadCatalog } from '../src/catalog.js'

const dataRoot = fileURLToPath(new URL('../data/', import.meta.url))
const indexPath = fileURLToPath(new URL('../skills/uiux/references/style-index.md', import.meta.url))

/** Render the index body, without the header comment. */
export function renderIndex(entries) {
  const full = entries.filter(entry => entry.depth === 'full')
  const brief = entries.filter(entry => entry.depth === 'brief')
  const lines = [
    '# Style index\n',
    '\n',
    `${full.length} authored styles carry full specs; ${brief.length} brief styles carry a palette and positioning only.\n`,
    'Both tiers resolve through `uiux_spec`; brief styles return tokens and overview sections without component recipes.\n',
    '\n',
    '## Full specs\n',
    '\n',
    '| slug | name | one-liner |\n',
    '| --- | --- | --- |\n',
  ]
  for (const entry of full) lines.push(`| \`${entry.slug}\` | ${entry.name} | ${entry.oneLiner} |\n`)
  lines.push('\n', '## Brief specs\n', '\n', '| slug | name | one-liner |\n', '| --- | --- | --- |\n')
  for (const entry of brief) lines.push(`| \`${entry.slug}\` | ${entry.name} | ${entry.oneLiner} |\n`)
  return lines.join('')
}

const entries = loadCatalog(dataRoot)
const header = '<!-- Generated by scripts/build-index.mjs from data/styles/*.json. Do not edit by hand. -->\n\n'
const body = renderIndex(entries)

if (process.argv.includes('--check')) {
  const current = readFileSync(indexPath, 'utf8')
  if (current !== header + body) {
    console.error('dsh-uiux: style index is stale; run `npm run build:index`')
    process.exit(1)
  }
  console.log('dsh-uiux: style index is current')
} else {
  writeFileSync(indexPath, header + body)
  console.log(`dsh-uiux: wrote style index for ${entries.length} styles`)
}
